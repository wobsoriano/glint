//! The Studio project (`project.json`): every edit made to a recording session.
//!
//! All `*_ms` times on clips and zooms are source media milliseconds. Output time is derived
//! by walking clips in order (see `timeline.rs`).
//!
//! Zooms are anchored to source time, not output time. A zoom frames something that happened
//! in the recording, typically a click, so it must stay attached to that moment when clips
//! before it are trimmed, deleted, sped up or cut by the transcript. Anchoring to output time
//! would make every such edit silently slide zooms onto unrelated footage. The camera motion
//! itself is still integrated along output time, so speed changes never make zooms snappier.

use anyhow::Context;
use glint_render::style::{Background, GRADIENTS};
use serde::{Deserialize, Serialize};
use std::path::Path;

pub const PROJECT_VERSION: u32 = 1;

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Project {
    pub version: u32,
    pub clips: Vec<Clip>,
    pub zooms: Vec<Zoom>,
    pub design: Design,
    pub aspect: AspectPreset,
    pub aspect_mode: AspectMode,
    /// Region of the screen master shown in the card, normalized to the source size.
    pub crop: CropRect,
    pub click_highlights: bool,
    pub keystrokes: KeystrokeSettings,
    pub captions: CaptionSettings,
    /// Caption lines in source time, made from the transcript and edited by hand.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub caption_cues: Vec<CaptionCue>,
    pub audio: AudioSettings,
    pub export: ExportOptions,
}

impl Default for Project {
    fn default() -> Self {
        Self {
            version: PROJECT_VERSION,
            clips: Vec::new(),
            zooms: Vec::new(),
            design: Design::default(),
            aspect: AspectPreset::Original,
            aspect_mode: AspectMode::Fit,
            crop: CropRect::FULL,
            click_highlights: true,
            keystrokes: KeystrokeSettings::default(),
            captions: CaptionSettings::default(),
            caption_cues: Vec::new(),
            audio: AudioSettings::default(),
            export: ExportOptions::default(),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Clip {
    pub start_ms: f64,
    pub end_ms: f64,
    #[serde(default = "one")]
    pub speed: f64,
}

fn one() -> f64 {
    1.0
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Zoom {
    pub start_ms: f64,
    pub end_ms: f64,
    /// Magnification while fully zoomed in (1 = none).
    #[serde(default = "default_zoom_scale")]
    pub scale: f32,
    #[serde(default)]
    pub focus: ZoomFocus,
    #[serde(default = "yes")]
    pub enabled: bool,
    /// Generated by auto zoom. Regenerating auto zoom replaces these and keeps manual ones.
    #[serde(default)]
    pub auto: bool,
}

fn default_zoom_scale() -> f32 {
    1.5
}

fn yes() -> bool {
    true
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ZoomFocus {
    #[default]
    Pointer,
    /// Normalized point inside the cropped screen card, top-left origin.
    Fixed { x: f32, y: f32 },
}

/// The part of a project a preset carries: background, layout, cursor and camera.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Design {
    pub background: Background,
    /// Card inset as a fraction of the canvas's short side.
    pub padding: f32,
    /// Card corner radius as a fraction of the canvas's short side.
    pub corner_radius: f32,
    /// Shadow strength, 0..=1.
    pub shadow: f32,
    pub cursor: CursorSettings,
    pub camera: CameraSettings,
}

impl Default for Design {
    fn default() -> Self {
        Self {
            background: Background::Gradient(GRADIENTS[0].1.clone()),
            padding: 0.06,
            corner_radius: 0.02,
            shadow: 0.45,
            cursor: CursorSettings::default(),
            camera: CameraSettings::default(),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct CursorSettings {
    pub visible: bool,
    /// Multiplier on the cursor's recorded size.
    pub size: f32,
    /// 0 draws raw pointer samples; 1 is the heaviest glide.
    pub smoothing: f32,
}

impl Default for CursorSettings {
    fn default() -> Self {
        Self { visible: true, size: 1.0, smoothing: 0.5 }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct CameraSettings {
    pub visible: bool,
    /// Normalized bubble center on the canvas, top-left origin.
    pub center: [f32; 2],
    /// Bubble diameter as a fraction of the canvas's short side.
    pub size: f32,
    /// Corner radius as a fraction of the diameter: 0.5 is a circle, 0 a square.
    pub roundness: f32,
}

impl Default for CameraSettings {
    fn default() -> Self {
        Self { visible: true, center: [0.85, 0.82], size: 0.26, roundness: 0.5 }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AspectPreset {
    Original,
    Wide16x9,
    Vertical9x16,
    Square,
    Portrait4x5,
}

impl AspectPreset {
    pub const ALL: [AspectPreset; 5] = [
        AspectPreset::Original,
        AspectPreset::Wide16x9,
        AspectPreset::Vertical9x16,
        AspectPreset::Square,
        AspectPreset::Portrait4x5,
    ];

    pub fn label(self) -> &'static str {
        match self {
            AspectPreset::Original => "Original",
            AspectPreset::Wide16x9 => "16:9",
            AspectPreset::Vertical9x16 => "9:16",
            AspectPreset::Square => "1:1",
            AspectPreset::Portrait4x5 => "4:5",
        }
    }

    /// Width over height; `None` keeps the recording's own aspect.
    pub fn ratio(self) -> Option<f32> {
        match self {
            AspectPreset::Original => None,
            AspectPreset::Wide16x9 => Some(16.0 / 9.0),
            AspectPreset::Vertical9x16 => Some(9.0 / 16.0),
            AspectPreset::Square => Some(1.0),
            AspectPreset::Portrait4x5 => Some(4.0 / 5.0),
        }
    }
}

/// How the recording occupies a canvas whose aspect differs from it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AspectMode {
    /// Crop into the recording with a camera that follows the pointer.
    Fill,
    /// Show the whole recording framed on the background.
    Fit,
}

