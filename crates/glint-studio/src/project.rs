impl Project {
    pub const FILE: &'static str = "project.json";

    /// A fresh project covering the whole recording.
    pub fn new(source_duration_ms: f64) -> Self {
        Self {
            clips: vec![Clip { start_ms: 0.0, end_ms: source_duration_ms, speed: 1.0 }],
            ..Self::default()
        }
    }

    /// Reads `project.json` from a session directory; a missing file means defaults.
    pub fn load(session_dir: &Path, source_duration_ms: f64) -> anyhow::Result<Self> {
        let path = session_dir.join(Self::FILE);
        let mut project = match std::fs::read_to_string(&path) {
            Ok(json) => serde_json::from_str::<Project>(&json)
                .with_context(|| format!("parsing {}", path.display()))?,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Project::default(),
            Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
        };
        project.normalize(source_duration_ms);
        Ok(project)
    }

    pub fn save(&self, session_dir: &Path) -> anyhow::Result<()> {
        let path = session_dir.join(Self::FILE);
        let tmp = path.with_extension("json.tmp");
        std::fs::write(&tmp, serde_json::to_string_pretty(self)?)
            .with_context(|| format!("writing {}", tmp.display()))?;
        std::fs::rename(&tmp, &path).with_context(|| format!("replacing {}", path.display()))?;
        Ok(())
    }

    /// Repairs a project read from disk: clips are clamped to the source, sorted, made
    /// non-overlapping, and an empty clip list becomes one clip over the whole recording.
    pub fn normalize(&mut self, source_duration_ms: f64) {
        self.version = PROJECT_VERSION;
        let dur = source_duration_ms.max(0.0);
        let mut clips: Vec<Clip> = self
            .clips
            .iter()
            .filter_map(|c| {
                let start = c.start_ms.clamp(0.0, dur);
                let end = c.end_ms.clamp(start, dur);
                let speed = if c.speed.is_finite() { c.speed } else { 1.0 };
                (end - start >= crate::timeline::MIN_CLIP_MS).then_some(Clip {
                    start_ms: start,
                    end_ms: end,
                    speed: speed.clamp(crate::timeline::MIN_SPEED, crate::timeline::MAX_SPEED),
                })
            })
            .collect();
        clips.sort_by(|a, b| a.start_ms.total_cmp(&b.start_ms));
        let mut prev_end = 0.0f64;
        clips.retain_mut(|c| {
            c.start_ms = c.start_ms.max(prev_end);
            let keep = c.end_ms - c.start_ms >= crate::timeline::MIN_CLIP_MS;
            if keep {
                prev_end = c.end_ms;
            }
            keep
        });
        if clips.is_empty() && dur > 0.0 {
            clips.push(Clip { start_ms: 0.0, end_ms: dur, speed: 1.0 });
        }
        self.clips = clips;
        self.zooms.retain(|z| z.end_ms > z.start_ms);
        self.zooms.sort_by(|a, b| a.start_ms.total_cmp(&b.start_ms));
        self.caption_cues.sort_by(|a, b| a.start_ms.total_cmp(&b.start_ms));
    }

    /// Canvas size for export: the aspect preset applied to the cropped recording, scaled so
    /// its short side matches the chosen resolution. Both sides are even for the encoder.
    pub fn output_size(&self, source: (u32, u32)) -> (u32, u32) {
        let vis_w = source.0 as f32 * self.crop.w;
        let vis_h = source.1 as f32 * self.crop.h;
        let (w, h) = match self.aspect.ratio() {
            None => {
                let p = self.design.padding.clamp(0.0, 0.475);
                let inset = vis_w.min(vis_h) * p / (1.0 - 2.0 * p);
                (vis_w + 2.0 * inset, vis_h + 2.0 * inset)
            }
            Some(r) if r < vis_w / vis_h => (vis_h * r, vis_h),
            Some(r) => (vis_w, vis_w / r),
        };
        let k = match self.export.resolution.short_side() {
            Some(s) => s as f32 / w.min(h),
            None => 1.0,
        };
        let even = |v: f32| ((v * k).round() as u32 & !1).max(2);
        (even(w), even(h))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn missing_fields_take_defaults() {
        let json = r#"{ "version": 1, "clips": [{ "start_ms": 0, "end_ms": 5000 }],
                        "zooms": [{ "start_ms": 100, "end_ms": 900 }] }"#;
        let p: Project = serde_json::from_str(json).unwrap();
        assert_eq!(p.clips[0].speed, 1.0);
        assert_eq!(p.zooms[0].scale, 1.5);
        assert_eq!(p.zooms[0].focus, ZoomFocus::Pointer);
        assert!(p.zooms[0].enabled);
        assert_eq!(p.export.fps, Fps::Fps60);
        assert_eq!(p.keystrokes.position, KeystrokePosition::BottomCenter);
    }

    #[test]
    fn load_repairs_overlapping_and_out_of_range_clips() {
        let dir = std::env::temp_dir().join(format!("glint-studio-load-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join(Project::FILE),
            r#"{ "clips": [{ "start_ms": 3000, "end_ms": 9000, "speed": 20 },
                           { "start_ms": 0, "end_ms": 4000 }] }"#,
        )
        .unwrap();
        let p = Project::load(&dir, 8000.0).unwrap();
        std::fs::remove_dir_all(&dir).ok();
        assert_eq!(
            p.clips,
            vec![
                Clip { start_ms: 0.0, end_ms: 4000.0, speed: 1.0 },
                Clip { start_ms: 4000.0, end_ms: 8000.0, speed: 8.0 },
            ]
        );
    }

    #[test]
    fn output_size_per_aspect() {
        let mut p = Project::new(1000.0);
        p.export.resolution = Resolution::P1080;
        p.aspect = AspectPreset::Wide16x9;
        assert_eq!(p.output_size((2560, 1440)), (1920, 1080));
        p.aspect = AspectPreset::Vertical9x16;
        assert_eq!(p.output_size((2560, 1440)), (1080, 1920));
        p.aspect = AspectPreset::Square;
        assert_eq!(p.output_size((2560, 1440)), (1080, 1080));
        p.aspect = AspectPreset::Original;
        p.design.padding = 0.0;
        p.export.resolution = Resolution::Source;
        assert_eq!(p.output_size((2560, 1440)), (2560, 1440));
    }
}
