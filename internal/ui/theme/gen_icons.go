//go:build ignore

// gen_icons writes icons_gen.go from the icon table of the Rust build, src/assets.rs.
//
//	go generate ./internal/ui/theme
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"github.com/wobsoriano/glint/internal/ui/theme/rusticons"
)

func main() {
	src, err := os.ReadFile("../../../src/assets.rs")
	if err != nil {
		log.Fatal(err)
	}
	icons := rusticons.Parse(string(src))
	if len(icons) == 0 {
		log.Fatal("no icons found in src/assets.rs")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_icons.go from src/assets.rs; DO NOT EDIT.\n\npackage theme\n\nconst (\n")
	for i, ic := range icons {
		if i == 0 {
			fmt.Fprintf(&b, "\tIcon%s IconName = iota\n", camel(ic.Name))
		} else {
			fmt.Fprintf(&b, "\tIcon%s\n", camel(ic.Name))
		}
	}
	b.WriteString("\ticonCount\n)\n\nvar iconNames = [iconCount]string{\n")
	for _, ic := range icons {
		fmt.Fprintf(&b, "\tIcon%s: %q,\n", camel(ic.Name), ic.Name)
	}
	b.WriteString("}\n\nvar iconBodies = [iconCount]string{\n")
	for _, ic := range icons {
		fmt.Fprintf(&b, "\tIcon%s: `%s`,\n", camel(ic.Name), ic.Body)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icons_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func camel(name string) string {
	var s strings.Builder
	for _, part := range strings.Split(name, "-") {
		s.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return s.String()
}
