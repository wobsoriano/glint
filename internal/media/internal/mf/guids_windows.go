func newGUID(d1 uint32, d2, d3 uint16, d4 [8]byte) GUID {
	return GUID{Data1: d1, Data2: d2, Data3: d3, Data4: d4}
}

// formatGUID is the media subtype for a FourCC or WAVE_FORMAT tag (DEFINE_MEDIATYPE_GUID).
func formatGUID(code uint32) GUID {
	return GUID{Data1: code, Data2: 0x0000, Data3: 0x0010, Data4: [8]byte{0x80, 0x00, 0x00, 0xAA, 0x00, 0x38, 0x9B, 0x71}}
}

